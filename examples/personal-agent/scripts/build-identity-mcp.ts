import { fileURLToPath } from "node:url";
import { build, write } from "bun";

// Development-only bundling; MCP clients use the committed asset.
for (const [entry, asset, handler] of [
  ["identity-mcp.ts", "identity-bootstrap.mcp.js", "runMcpIdentity"],
  [
    "identity-incremental.ts",
    "identity-incremental.mcp.js",
    "runIncrementalIdentity",
  ],
]) {
  const result = await build({
    entrypoints: [fileURLToPath(new URL(`../${entry}`, import.meta.url))],
    target: "browser",
    format: "esm",
    minify: { whitespace: true, syntax: true, identifiers: false },
  });
  if (!result.success) throw new Error(result.logs.map(String).join("\n"));
  await write(
    new URL(`../${asset}`, import.meta.url),
    `// biome-ignore-all format: generated, minified MCP asset
// biome-ignore-all lint: generated bundle includes third-party code
// Generated by bun run build:identity-mcp; append a default handler calling ${handler}.
${await result.outputs[0].text()}`
  );
}

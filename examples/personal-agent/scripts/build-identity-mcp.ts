import { fileURLToPath } from "node:url";
import { build, write } from "bun";

// Development-only bundling; MCP clients use the committed asset.
const result = await build({
  entrypoints: [fileURLToPath(new URL("../identity-mcp.ts", import.meta.url))],
  target: "browser",
  format: "esm",
  minify: { whitespace: true, syntax: true, identifiers: false },
});
if (!result.success) throw new Error(result.logs.map(String).join("\n"));
await write(
  new URL("../identity-bootstrap.mcp.js", import.meta.url),
  `// biome-ignore-all format: generated, minified MCP asset
// biome-ignore-all lint: generated bundle includes third-party code
// Generated by bun run build:identity-mcp; append a default handler calling runMcpIdentity.
${await result.outputs[0].text()}`
);

-- Additive registry and nullable receipt identity: old replicas keep working.
-- No table rewrite or data backfill. The two VALIDATE scans are O(runs rows)
-- under SHARE UPDATE EXCLUSIVE; separate autocommit statements release the
-- short ADD COLUMN/CONSTRAINT locks before those scans. Not benchmarked at the
-- production row count; integration tests use disposable PostgreSQL 18.
CREATE TABLE IF NOT EXISTS action_types (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id TEXT NOT NULL REFERENCES organization(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  name TEXT NOT NULL,
  -- squawk-ignore prefer-bigint-over-int -- bounded published revision counter, not a row identifier
  current_version INTEGER NOT NULL DEFAULT 0 CHECK (current_version >= 0),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_by_user_id TEXT REFERENCES "user"(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,
  UNIQUE (organization_id, key)
);

CREATE TABLE IF NOT EXISTS action_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action_type_id BIGINT NOT NULL REFERENCES action_types(id) ON DELETE CASCADE,
  -- squawk-ignore prefer-bigint-over-int -- bounded published revision counter, not a row identifier
  version INTEGER NOT NULL CHECK (version > 0),
  definition JSONB NOT NULL,
  created_by_user_id TEXT REFERENCES "user"(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,
  UNIQUE (action_type_id, version),
  UNIQUE (action_type_id, id)
);

ALTER TABLE runs
  ADD COLUMN IF NOT EXISTS action_type_id BIGINT,
  ADD COLUMN IF NOT EXISTS action_version_id BIGINT;

DO $migration$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'runs'::regclass AND conname = 'runs_typed_action_pair'
  ) THEN
    ALTER TABLE runs ADD CONSTRAINT runs_typed_action_pair CHECK (
      (action_type_id IS NULL AND action_version_id IS NULL)
      OR (action_type_id IS NOT NULL AND action_version_id IS NOT NULL AND run_type = 'action')
    ) NOT VALID;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'runs'::regclass AND conname = 'runs_typed_action_version_fkey'
  ) THEN
    ALTER TABLE runs ADD CONSTRAINT runs_typed_action_version_fkey
      FOREIGN KEY (action_type_id, action_version_id)
      REFERENCES action_versions(action_type_id, id)
      DEFERRABLE INITIALLY DEFERRED NOT VALID;
  END IF;
END
$migration$;

-- squawk-ignore prefer-robust-stmts -- validation is retry-safe; separate autocommit releases the earlier exclusive lock
ALTER TABLE runs VALIDATE CONSTRAINT runs_typed_action_pair;
-- squawk-ignore prefer-robust-stmts -- validation is retry-safe; separate autocommit releases the earlier exclusive lock
ALTER TABLE runs VALIDATE CONSTRAINT runs_typed_action_version_fkey;

-- The existing org-scoped action_idempotency_key UNIQUE index serializes
-- command reservation. Typed commands use a server-owned key prefix.
-- Referenced revisions cannot be removed while receipts survive. Deferred
-- checking permits the existing whole-workspace purge in any FK order.

